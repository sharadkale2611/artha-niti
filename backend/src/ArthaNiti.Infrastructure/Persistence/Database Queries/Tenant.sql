IF OBJECT_ID(N'Tenants', N'U') IS NULL
BEGIN
CREATE TABLE Tenants (TenantId INT IDENTITY(1,1) PRIMARY KEY, 
		TenantCode VARCHAR(50) NOT NULL UNIQUE,
		TenantName VARCHAR(200) NOT NULL, 
		Slug VARCHAR(150) NOT NULL UNIQUE, 
		Email VARCHAR(256) NULL, 
		PhoneNumber VARCHAR(30) NULL, 
		Status INT NOT NULL DEFAULT 1 CHECK (Status IN (1, 2, 3, 4)), 
		IsActive BIT NOT NULL DEFAULT 1, 
		IsDeleted BIT NOT NULL DEFAULT 0, 
		CreatedAt DATETIME NOT NULL DEFAULT GETDATE(), 
		CreatedBy VARCHAR(450) NULL, 
		UpdatedAt DATETIME NULL, 
		UpdatedBy VARCHAR(450) NULL);
END
