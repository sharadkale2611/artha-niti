IF OBJECT_ID(N'Permissions', N'U') IS NULL
BEGIN
CREATE TABLE Permissions
(
		PermissionId INT IDENTITY(1,1) PRIMARY KEY, 
		Code VARCHAR(150) NOT NULL,
		Name VARCHAR(150) NOT NULL,
		Description VARCHAR(500) NULL,
		ModuleCode VARCHAR(100) NOT NULL,
		PluginCode VARCHAR(100) NULL,
		PermissionScope INT NOT NULL DEFAULT 2,
		IsSystemPermission BIT NOT NULL DEFAULT 0,
		IsActive BIT NOT NULL DEFAULT 1,
		IsDeleted BIT NOT NULL DEFAULT 0, 
		CreatedAt DATETIME NOT NULL DEFAULT GETDATE(),
		CreatedBy VARCHAR(450) NULL, 
		UpdatedAt DATETIME NULL,
		UpdatedBy VARCHAR(450) NULL
)
END
